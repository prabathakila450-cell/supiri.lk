      in 11..15 -> "පදාර්ථයේ ව්‍යුහය සහ ආවර්තිතා වගුව"
      in 16..20 -> "රසායනික බන්ධන සහ සංයුජතාව"
      in 21..25 -> "චලිත සමීකරණ හා ප්‍රවේග-කාල ප්‍රස්තාර"
      in 26..30 -> "නිව්ටන්ගේ චලිත නියම සහ බලය"
      in 31..35 -> "ශාක හා සත්ත්ව පටක"
      in 36..40 -> "රුධිර සංසරණ පද්ධතිය හා හෘදය"
      in 41..45 -> "රසායනික ප්‍රතික්‍රියා සහ උදාසීනීකරණය"
