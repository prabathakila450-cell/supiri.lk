      else -> "පරිසර විද්‍යාව සහ සම්පත් කළමනාකරණය"
    }

    val offset = (term * 100) + (paperIdx * 60) + qNum
    val (qText, opts, correctIdx, exp) = getScienceTopicData(topic, qNum, offset, grade)

    return MockExamQuestion(
      id = qNum,
      questionText = "[$qNum] $qText",
      options = opts,
      correctOption = correctIdx,
      explanation = exp,
      topicName = topic
    )
  }

