  private fun generateScienceQuestion(grade: String, term: Int, paperIdx: Int, qNum: Int): MockExamQuestion {
    val topic = when (qNum) {
      in 1..5 -> "ජෛව අණු සහ සෛලීය ව්‍යුහය"
