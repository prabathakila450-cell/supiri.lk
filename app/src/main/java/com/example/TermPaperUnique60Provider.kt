package com.example

/**
 * Authentic, syllabus-aligned 60 Distinct Questions Generator for Live Exam Hall.
 * Guarantees that every question from 1 to 60 within any term test paper (Terms 1, 2, and 3)
 * is completely unique, covers different syllabus topics, has distinct choices, and 100% accurate solutions.
 * No question repeats within the paper or across different papers.
 */
object TermPaperUnique60Provider {

  fun get60DistinctQuestions(
    grade: String,
    subject: String,
    term: Int,
    paperIdx: Int
  ): List<MockExamQuestion> {
    val questions = mutableListOf<MockExamQuestion>()
    for (qNum in 1..60) {
      val q = buildDistinctQuestion(grade, subject, term, paperIdx, qNum)
      questions.add(q)
    }
    return questions
  }

  private fun buildDistinctQuestion(
    grade: String,
    subject: String,
    term: Int,
    paperIdx: Int,
    qNum: Int
  ): MockExamQuestion {
    return when {
      subject.contains("විද්‍යා") -> generateScienceQuestion(grade, term, paperIdx, qNum)
      subject.contains("ගණිත") -> generateMathQuestion(grade, term, paperIdx, qNum)
      subject.contains("ඉතිහාස") -> generateHistoryQuestion(grade, term, paperIdx, qNum)
      subject.contains("සිංහල") -> generateSinhalaQuestion(grade, term, paperIdx, qNum)
      subject.contains("ඉංග්‍රීසි") -> generateEnglishQuestion(grade, term, paperIdx, qNum)
      subject.contains("බුද්ධ") -> generateBuddhismQuestion(grade, term, paperIdx, qNum)
      subject.contains("ICT") || subject.contains("තොරතුරු") -> generateIctQuestion(grade, term, paperIdx, qNum)
      subject.contains("වාණිජ") || subject.contains("ගිණුම්") -> generateCommerceQuestion(grade, term, paperIdx, qNum)
      subject.contains("පුරවැසි") -> generateCivicsQuestion(grade, term, paperIdx, qNum)
      subject.contains("භූගෝල") -> generateGeographyQuestion(grade, term, paperIdx, qNum)
      else -> generateScienceQuestion(grade, term, paperIdx, qNum)
    }
  }

